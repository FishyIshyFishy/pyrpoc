"""The recording format: a ``<stem>_meta.json`` that names its data files, and
how it is written and read."""

from __future__ import annotations

import importlib.metadata
import json
import os
from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path
from typing import Any

from pyrpoc.core.program_output import Data, Origin, ProgramOutput, Provenance, data_kind_registry
from pyrpoc.core.saving import writer_registry

from .grouping import program_display_name

FORMAT = "pyrpoc-recording"
FORMAT_VERSION = 4
META_SUFFIX = "_meta.json"
# Every note in an Experiment, in one file a person can read without the app.
NOTES_FILE = "notes.txt"
NOTES_FILE_HEADER = (
    "Generated by pyrpoc from the notes saved with each recording in this folder.\n"
    "Edits made here are overwritten: edit a note in the app's Data Library instead."
)


class RecordingError(Exception):
    """A recording on disk that cannot be read. The message names the file."""


@dataclass
class RunRecord:
    run_id: int
    started_at: str
    ended_at: str | None
    error: str | None


@dataclass
class OutputRecord:
    kind: str
    # Values published; the files hold every one.
    published: int
    # File names beside the metadata file, keyed as the writer keyed them.
    files: dict[str, str]
    metadata: dict[str, Any]


@dataclass
class RecordingRecord:
    pyrpoc_version: str
    program_key: str
    name: str
    started_at: str
    ended_at: str | None
    last_error: str | None
    runs: list[RunRecord]
    parameters: dict[str, Any]
    devices: dict[str, Any]
    outputs: dict[str, OutputRecord]
    # What the user wrote about the run, before or after it.
    notes: str


def pyrpoc_version() -> str:
    return importlib.metadata.version("pyrpoc")


def meta_path_for(root: Path) -> Path:
    return root.with_name(f"{root.name}{META_SUFFIX}")


def recordings_in(folder: Path) -> list[Path]:
    """The metadata file of every recording in ``folder``, by name."""
    return sorted(folder.glob(f"*{META_SUFFIX}"))


def free_root(root: Path) -> Path:
    """``root``, or the first of ``root_2``, ``root_3`` and so on that has no recording
    yet."""
    candidate, number = root, 1
    while meta_path_for(candidate).exists():
        number += 1
        candidate = root.with_name(f"{root.name}_{number}")
    return candidate


def write_record(meta_path: Path, record: RecordingRecord) -> None:
    write_json(meta_path, {"format": FORMAT, "format_version": FORMAT_VERSION, **asdict(record)})


def write_json(path: Path, payload: dict[str, Any]) -> None:
    write_text(path, json.dumps(payload, indent=2, default=str))


def write_text(path: Path, text: str) -> None:
    """Replace ``path`` whole."""
    # So a crash mid-write never leaves half a file.
    partial = path.with_name(f"{path.name}.partial")
    partial.write_text(text, encoding="utf-8")
    os.replace(partial, path)


def read_json(meta_path: Path) -> dict[str, Any]:
    """The metadata file's JSON, checked to be a recording this version reads."""
    try:
        raw = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RecordingError(f"cannot read {meta_path}: {exc}") from exc
    if not isinstance(raw, dict) or raw.get("format") != FORMAT:
        raise RecordingError(f"{meta_path} is not a pyrpoc recording")
    version = raw.get("format_version")
    if version != FORMAT_VERSION:
        raise RecordingError(
            f"{meta_path} is recording format {version!r}; this version of pyrpoc reads "
            f"format {FORMAT_VERSION}"
        )
    return raw


def read_record(meta_path: Path) -> RecordingRecord:
    raw = read_json(meta_path)
    try:
        return decode_record(raw)
    except (KeyError, TypeError, ValueError, AttributeError) as exc:
        raise RecordingError(f"{meta_path} is malformed: {exc!r}") from exc


def optional_str(value: Any) -> str | None:
    return None if value is None else str(value)


def decode_record(raw: dict[str, Any]) -> RecordingRecord:
    """The recording a metadata file's JSON describes."""
    # Unknown fields are ignored, so a format may add some.
    return RecordingRecord(
        pyrpoc_version=str(raw["pyrpoc_version"]),
        program_key=str(raw["program_key"]),
        name=str(raw["name"]),
        started_at=str(raw["started_at"]),
        ended_at=optional_str(raw["ended_at"]),
        last_error=optional_str(raw["last_error"]),
        runs=[
            RunRecord(
                run_id=int(run["run_id"]),
                started_at=str(run["started_at"]),
                ended_at=optional_str(run["ended_at"]),
                error=optional_str(run["error"]),
            )
            for run in raw["runs"]
        ],
        parameters=dict(raw["parameters"]),
        devices=dict(raw["devices"]),
        outputs={
            str(output): OutputRecord(
                kind=str(entry["kind"]),
                published=int(entry["published"]),
                files={str(key): str(name) for key, name in entry["files"].items()},
                metadata=dict(entry["metadata"]),
            )
            for output, entry in raw["outputs"].items()
        },
        notes=str(raw["notes"]),
    )


def load_recording(meta_path: Path) -> tuple[list[ProgramOutput[Any]], str]:
    """Every output of the recording at ``meta_path``, each holding the last
    value it was published, and the recording's note."""
    record = read_record(meta_path)
    outputs = [
        load_output(meta_path, record, output, entry) for output, entry in record.outputs.items()
    ]
    return outputs, record.notes


def load_output(
    meta_path: Path, record: RecordingRecord, output: str, entry: OutputRecord
) -> ProgramOutput[Any]:
    if entry.kind not in data_kind_registry.keys():
        raise RecordingError(f"{meta_path}: output {output!r} is of unknown kind {entry.kind!r}")
    kind = data_kind_registry.get(entry.kind)
    program_output = ProgramOutput(
        name=output,
        kind=kind,
        provenance=Provenance(
            program_key=record.program_key,
            started_at=record.started_at,
            name=record.name,
            parameters=record.parameters,
            devices=record.devices,
            run_id=record.runs[0].run_id if record.runs else 0,
        ),
        origin=Origin.LOADED,
        writer=None,
    )
    program_output.metadata = dict(entry.metadata)
    program_output.meta_path = meta_path
    program_output.value = read_value(meta_path, output, kind, entry)
    program_output.published = entry.published
    return program_output


def read_value(meta_path: Path, output: str, kind: type[Data], entry: OutputRecord) -> Data | None:
    files = {key: meta_path.parent / name for key, name in entry.files.items()}
    missing = [path.name for path in files.values() if not path.is_file()]
    if missing:
        raise RecordingError(f"{meta_path}: output {output!r} is missing {', '.join(missing)}")
    if not files:
        return None
    try:
        return writer_registry.get(entry.kind).read(kind, files)
    except (OSError, ValueError, KeyError) as exc:
        raise RecordingError(f"{meta_path}: cannot read output {output!r}: {exc}") from exc


def write_notes(meta_path: Path, notes: str) -> None:
    """Set the note in a finished recording's metadata file."""
    # Edited as raw JSON, so fields this version does not know survive.
    raw = read_json(meta_path)
    raw["notes"] = notes
    write_json(meta_path, raw)


def write_folder_notes(folder: Path) -> None:
    """Rebuild ``notes.txt`` in ``folder`` from the notes of the recordings in it, oldest
    first; with no notes, there is no file."""
    # Rebuilt from disk every time, so it never holds duplicates or falls out of step, and two
    # runs saving into one folder cannot interleave their entries.
    entries = sorted(
        (record.started_at, note_entry(record))
        for record in readable_records(folder)
        if record.notes.strip()
    )
    path = folder / NOTES_FILE
    if not entries:
        path.unlink(missing_ok=True)
        return
    text = "\n\n".join([NOTES_FILE_HEADER, *(entry for _, entry in entries)]) + "\n"
    write_text(path, text)


def readable_records(folder: Path) -> list[RecordingRecord]:
    """Every recording in ``folder`` that can be read; the rest are left out."""
    # A broken recording is reported when it is opened; it must not stop the others' notes.
    records: list[RecordingRecord] = []
    for meta_path in recordings_in(folder):
        try:
            records.append(read_record(meta_path))
        except RecordingError:
            continue
    return records


def note_entry(record: RecordingRecord) -> str:
    """One recording's entry: when it was taken, its name and program, then its note."""
    when = datetime.fromisoformat(record.started_at).astimezone().strftime("%Y-%m-%d %H:%M")
    name = record.name or record.program_key
    heading = f"{when}  {name}  ({program_display_name(record.program_key)})"
    note = "\n".join(f"    {line}" for line in record.notes.strip().splitlines())
    return f"{heading}\n{note}"
