"""Phase 2.5: one note per run, written before it, saved with it, and gathered per Experiment."""

from __future__ import annotations

import json
import time
from pathlib import Path

from pyrpoc.core.program_input import program_input_registry
from pyrpoc.core.program_output import ProgramOutput
from pyrpoc.core.saving import SaveTarget
from pyrpoc.engine.data_library.format import NOTES_FILE
from pyrpoc.engine.data_library.model import LibraryModel
from pyrpoc.engine.data_library.store import LibraryStore

from .helpers import FrameProgram, Harness, SpectrumProgram, saving_into
from .qt import application, qt_app


def library_over(harness: Harness) -> LibraryModel:
    return LibraryModel(harness.library, qt_app())


def notes_text(folder: Path) -> str:
    return (folder / NOTES_FILE).read_text(encoding="utf-8")


def test_a_note_written_before_a_run_is_in_its_details_and_notes_txt(tmp_path: Path) -> None:
    harness = Harness()
    run = harness.run(FrameProgram(), "test_frame", saving_into(tmp_path, "beads"), "40x, dim")
    library = library_over(harness)

    [output] = run.outputs.values()
    assert library.note_of(output) == "40x, dim"
    meta = json.loads((tmp_path / "beads_meta.json").read_text(encoding="utf-8"))
    assert meta["notes"] == "40x, dim"
    assert all("notes" not in entry for entry in meta["outputs"].values())
    text = notes_text(tmp_path)
    assert text.startswith("Generated by pyrpoc")
    # The test program is not registered, so it goes by its key.
    assert "beads  (test_frame)" in text and "    40x, dim" in text


def test_editing_a_note_in_the_library_updates_the_file_and_notes_txt(tmp_path: Path) -> None:
    harness = Harness()
    run = harness.run(FrameProgram(), "test_frame", saving_into(tmp_path, "beads"), "first")
    library = library_over(harness)
    [output] = run.outputs.values()

    assert library.set_note(output, "second thoughts") is None
    meta = json.loads((tmp_path / "beads_meta.json").read_text(encoding="utf-8"))
    assert meta["notes"] == "second thoughts"
    assert "second thoughts" in notes_text(tmp_path)
    assert "first" not in notes_text(tmp_path)

    # Reopened from disk, the note comes back with the recording.
    reopened = LibraryModel(LibraryStore(1 << 30), qt_app())
    reopened.load_experiment(tmp_path)
    assert reopened.note_of(reopened.all()[0]) == "second thoughts"


def test_entries_are_in_time_order_and_only_for_saved_runs_with_a_note(tmp_path: Path) -> None:
    harness = Harness()
    harness.run(FrameProgram(), "test_frame", saving_into(tmp_path, "early"), "one")
    time.sleep(0.01)
    harness.run(SpectrumProgram(), "test_spectrum", saving_into(tmp_path, "silent"), "")
    unsaved = SaveTarget(name="loose", directory=str(tmp_path), enabled=False)
    loose = harness.run(FrameProgram(), "test_frame", unsaved, "kept in memory only")
    time.sleep(0.01)
    harness.run(SpectrumProgram(), "test_spectrum", saving_into(tmp_path, "late"), "two")

    text = notes_text(tmp_path)
    assert text.index("early") < text.index("late")
    assert "silent" not in text and "loose" not in text and "kept in memory" not in text
    [loose_output] = loose.outputs.values()
    assert library_over(harness).note_of(loose_output) == "kept in memory only"


def test_no_note_anywhere_means_no_notes_txt(tmp_path: Path) -> None:
    harness = Harness()
    harness.run(FrameProgram(), "test_frame", saving_into(tmp_path, "plain"))
    assert not (tmp_path / NOTES_FILE).exists()


def test_notes_are_not_on_program_outputs_or_program_inputs(tmp_path: Path) -> None:
    run = Harness().run(FrameProgram(), "test_frame", saving_into(tmp_path, "beads"), "a note")
    [output] = run.outputs.values()
    assert isinstance(output, ProgramOutput) and "notes" not in vars(output)
    application()
    assert not [key for key in program_input_registry if "note" in key.lower()]


def test_the_notes_box_clears_once_a_run_takes_it(tmp_path: Path) -> None:
    app = application()
    runs = app.runs
    runs.set_save(name="cells", directory=str(tmp_path), enabled=True)
    runs.set_note("before the run")
    finished: list[object] = []
    runs.events.run_finished.connect(finished.append)
    runs.start("simulation", None, lambda _run: None)
    assert runs.note == ""
    deadline = time.monotonic() + 10
    while not finished and time.monotonic() < deadline:
        qt_app().processEvents()
        time.sleep(0.01)
    [output] = app.library.all()
    assert app.library.note_of(output) == "before the run"
    assert "before the run" in notes_text(tmp_path)
